WEEKDAYS = ["monday", "tuesday", "wednesday", "thursday", "friday"]

def _scrape_restaurant(scraper_cls, day, cached_scraper=None):
    """Run one restaurant, including sequential retries, in a single worker."""
    max_retries = 2
    sweden_tz = timezone(timedelta(hours=2))
    for attempt in range(1, max_retries + 2):
        try:
            scraper = cached_scraper if cached_scraper is not None else scraper_cls()
            all_menus = scraper.get_all_menus()
            if all_menus:
                cached_scraper = scraper
                menu = all_menus.get(day.lower())
            else:
                menu = scraper.get_menu_for_day(day)
            if not menu:
                logging.warning("No menu found for %s on %s", scraper_cls.__name__, day)
                return None, cached_scraper

            result = {
                "day": menu.day,
                "last_scraped": datetime.now(sweden_tz).strftime("%Y-%m-%d"),
                "items": [
                    {
                        "name": item.name,
                        "category": item.category or "",
                        "description": item.description or "",
                        "price": item.price or "",
                        # Tags will be re-generated by annotate_file().
                    }
                    for item in menu.items
                ],
            }
            return result, cached_scraper
        except Exception as exc:
            logging.error("[%s] Error on attempt %s for %s: %s",
                          scraper_cls.__name__, attempt, day, exc)
            traceback.print_exc()
            if attempt > max_retries:
                logging.warning("[%s] Gave up after %s retries.",
                                scraper_cls.__name__, max_retries)
            else:
                delay = 2 + attempt
                logging.info("[%s] Retrying in %s seconds...", scraper_cls.__name__, delay)
                time.sleep(delay)
    return None, cached_scraper


def scrape_for_day(day: str, refresh: bool = False, cache: dict = None):
    logging.info(f"Scraping lunch menus for {day.capitalize()}")

    filepath = f"data/lunch_data_{day}.json"
    existing_data = {}

    # Load existing data as a fallback/baseline
    if os.path.exists(filepath):
        try:
            with open(filepath, encoding="utf-8") as f:
                existing_data = json.load(f)
            logging.info(f"Loaded existing data for {day} from {filepath} "
                         f"({len(existing_data)} restaurants).")
        except Exception as e:
            logging.warning(f"Failed to read existing data for {day} from {filepath}: {e}")

    # If we already have data and we're NOT forcing refresh, just regenerate HTML
    if os.path.exists(filepath) and not refresh:
        logging.info(f"Skipping scraping for {day} (cached file exists and refresh is False).")
        generate_lunch_summary(day)
        return

    # Start from existing data; we'll override per restaurant on successful scrape
    results = dict(existing_data)

    # One task owns a restaurant's complete retry sequence. Days are still
    # processed sequentially, so cached weekly instances are never used by
    # multiple workers at once. Only this thread merges results and cache data.
    scraper_classes = list(dict.fromkeys(SCRAPERS))
    cached_scrapers = [cache.get(cls.__name__) if cache is not None else None
                       for cls in scraper_classes]
    with ThreadPoolExecutor(max_workers=5) as executor:
        outcomes = executor.map(
            _scrape_restaurant, scraper_classes,
            [day] * len(scraper_classes), cached_scrapers,
        )
        for scraper_cls, (result, weekly_scraper) in zip(scraper_classes, outcomes):
            if result is not None:
                results[scraper_cls.__name__] = result
            if cache is not None and weekly_scraper is not None:
                cache[scraper_cls.__name__] = weekly_scraper

    # results will contain:
    # - existing restaurants (fallback) for which scraping failed or was skipped
    # - updated restaurants for which scraping succeeded
    if results:
        os.makedirs("data", exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(results, f, indent=2, ensure_ascii=False)
        logging.info(
            f"Wrote lunch data to {filepath} "
            f"({len(results)} restaurants, including fallbacks)."
        )
    else:
        logging.warning(
            f"No results to write for {day} and no fallback data existed. "
            "Skipping JSON and HTML."
        )
        return

    generate_lunch_summary(day)

def main():
    parser = argparse.ArgumentParser(description="Run Lindholmen lunch scrapers.")
    parser.add_argument("--day", type=str, help="Weekday to scrape (e.g., monday)", choices=WEEKDAYS)
    parser.add_argument("--all", action="store_true", help="Scrape all weekdays (mon–fri)")
    parser.add_argument("--refresh", action="store_true", help="Force re-scraping even if data exists")

    args = parser.parse_args()

    if args.all:
        weekly_scraper_cache = {}
        for day in WEEKDAYS:
            scrape_for_day(day, refresh=args.refresh, cache=weekly_scraper_cache)
    else:
        day = args.day or get_today_english()
        scrape_for_day(day, refresh=args.refresh)

if __name__ == "__main__":
    main()
    generate_index_page()
